export function cloneWordBank(bank: DrawGuessWordBank): DrawGuessWordBank {
  const next: DrawGuessWordBank = {}
  for (const [name, words] of Object.entries(bank)) {
    next[name] = [...words]
  }
  return next
}

export function wordBankToCategories(bank: DrawGuessWordBank) {
  return Object.entries(bank).map(([name, words], index) => ({
    key: `${name}-${index}`,
    name,
    wordsText: words.join('\n')
  }))
}

export function categoriesToWordBank(categories: Array<{ name: string; wordsText: string }>): DrawGuessWordBank {
  const bank: DrawGuessWordBank = {}
  for (const item of categories) {
    const name = String(item.name || '').trim()
    if (!name) continue
    const words = String(item.wordsText || '')
      .split(/\r?\n/)
      .map((w) => w.trim())
      .filter(Boolean)
    const unique = [...new Set(words)]
    if (unique.length >= 2) bank[name] = unique
  }
  return bank
}

export function applyDrawGuessPreset(presetId: string) {
  const preset = DRAW_GUESS_WORD_PRESETS.find((p) => p.id === presetId)
  if (!preset) return null
  return {
    activePresetId: preset.id,
    styleName: preset.styleName,
    wordBank: cloneWordBank(preset.wordBank)
  }
}
